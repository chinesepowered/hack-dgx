// Click through the whole demo and take screenshots: node scripts/flow.mjs <outdir> [baseUrl]
import { chromium } from "playwright"
const [out = "/tmp/flow", base = "http://localhost:5173"] = process.argv.slice(2)
const api = (p, body = {}) => fetch(`${base}${p}`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }).then((r) => r.json())
const state = () => fetch(`${base}/api/state`).then((r) => r.json())
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

await api("/api/reset", { mode: "replay" })
const browser = await chromium.launch({ args: ["--autoplay-policy=no-user-gesture-required"] })
const page = await browser.newPage({ viewport: { width: 1400, height: 920 } })
page.on("pageerror", (e) => console.log("page error:", e.message))
page.on("console", (m) => m.type() === "error" && console.log("console:", m.text()))
let n = 0
const shot = async (name) => {
  await page.screenshot({ path: `${out}/${String(++n).padStart(2, "0")}-${name}.png` })
  console.log("shot", name)
}
await page.goto(base, { waitUntil: "load" })
await sleep(1200)
await page.getByRole("button", { name: /Tuck in/ }).click()
await sleep(9000)
await shot("trail-running")
await page.locator(".night").evaluate((el) => el.scrollTo(0, 0))
for (let i = 0; i < 60 && (await state()).nightShift.status !== "done"; i++) await sleep(500)
await sleep(800)
await shot("trail-done")
await page.getByRole("button", { name: /Wake up/ }).click()
await sleep(3400)
await sleep(1200)
await shot("delivery")
await sleep(2600)
await shot("paper-top")
const scroller = page.locator(".paper")
await scroller.evaluate((el) => el.scrollBy(0, 560))
await sleep(500)
await shot("paper-2")
await scroller.evaluate((el) => el.scrollBy(0, 640))
await sleep(500)
await shot("paper-3")
await scroller.evaluate((el) => el.scrollBy(0, 640))
await sleep(500)
await shot("paper-4")
await scroller.evaluate((el) => el.scrollBy(0, 900))
await sleep(500)
await shot("paper-5")
// approve everything
const s = await state()
for (const item of s.paper.items) {
  if (item.kind === "call" && s.paper.items.some((c) => c.kind === "conflict" && c.callId === item.id)) continue
  if (item.kind === "promise" && item.status === "upcoming" && item.direction === "owed_to_you") {
    await api(`/api/items/${item.id}/skip`)
    continue
  }
  await api(`/api/items/${item.id}/approve`)
}
await sleep(800)
await scroller.evaluate((el) => el.scrollTo(0, 0))
await sleep(600)
await shot("approved-top")
await api("/api/jump", { to: "09:00", lead: 2 })
await sleep(4500)
await shot("call-ringing")
await sleep(14000)
await shot("call-mid")
await api("/api/advance", { seconds: 36 })
await sleep(3000)
await shot("call-after-skip")
await api("/api/advance", { seconds: 30 })
await sleep(2500)
await shot("call-outcome")
await sleep(9000)
await shot("call2-start")
await api("/api/advance", { seconds: 80 })
await sleep(2500)
await shot("call2-outcome")
await page.getByRole("button", { name: /Back to the paper/ }).click()
await sleep(1500)
await shot("paper-after-calls")
await page.locator(".paper").evaluate((el) => el.scrollTo(0, 1250))
await sleep(600)
await shot("paper-conflict-moved")
await browser.close()
